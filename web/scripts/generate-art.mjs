import fs from "node:fs";
import solc from "solc";
import { encodeFunctionData, decodeFunctionResult, toHex, pad } from "viem";
import { rpc } from "./rpc.mjs";
const url = process.argv[2];
if (!url)
  throw Error(
    "Pass a public RPC URL to regenerate the preserved Renderer art.",
  );
const h = JSON.parse(
    fs.readFileSync(new URL("../deployment-handoff.json", import.meta.url)),
  ),
  r = h.contracts.find((c) => c.name === "Registry"),
  renderer = h.contracts.find((c) => c.name === "Renderer"),
  abi = JSON.parse(
    fs.readFileSync(new URL("../public/abi/Renderer.json", import.meta.url)),
  );
const publicWallet = JSON.parse(
  fs.readFileSync(
    new URL("../../docs/frontend/live-deployment.json", import.meta.url),
  ),
).publicContributors[0];
const ids = [
  101, 201, 202, 301, 302, 303, 401, 402, 403, 404, 501, 502, 503, 601, 701,
  801, 901, 1001, 1101, 1102, 1103, 1104, 1105, 1201, 1301,
];
const source = `pragma solidity 0.8.24; struct Spec {uint8 kind;address target;string item;string arg;string fixedArg;uint256 fixedVal;string sumArg;uint8 op;uint256 threshold;uint64 fromBlock;uint64 toBlock;string name;} contract Illustration {uint256 public selected;uint256 public community;function claimantOf(uint256) external pure returns(address){return ${publicWallet};}function traitsOf(address) external view returns(uint16[] memory a){if(selected==0){a=new uint16[](25);${ids.map((id, i) => `a[${i}]=${id};`).join("")}}else{a=new uint16[](1);a[0]=uint16(selected);}}function verifiedSpecsOf(address) external view returns(uint16[] memory a){a=new uint16[](community);for(uint256 i;i<community;++i){a[i]=uint16(10001+i);}}function verified(address,uint16) external pure returns(bytes32,bytes32,uint64,uint64){return(0,0,0,0);}function specOf(uint16) external pure returns(Spec memory s){s.kind=5;s.name="Illustration";}}`;
const compiled = JSON.parse(
  solc.compile(
    JSON.stringify({
      language: "Solidity",
      sources: { "Illustration.sol": { content: source } },
      settings: {
        optimizer: { enabled: true, runs: 200 },
        evmVersion: "cancun",
        outputSelection: { "*": { "*": ["evm.deployedBytecode.object"] } },
      },
    }),
  ),
);
const code =
  "0x" +
  compiled.contracts["Illustration.sol"].Illustration.evm.deployedBytecode
    .object;
const dir = new URL("../public/art/", import.meta.url);
fs.mkdirSync(dir, { recursive: true });
// selected 0 shows all 25 catalog facts; -1 also adds 32 community facts
// (the most a card displays): the full-house card shown in the header.
for (const id of [0, ...ids, -1]) {
  const data = encodeFunctionData({
    abi,
    functionName: "tokenURIOf",
    args: [r.address, 1n],
  });
  const result = rpc(url, "eth_call", [
    { to: renderer.address, data },
    "latest",
    {
      [r.address]: {
        code,
        stateDiff: {
          [pad("0x0", { size: 32 })]: pad(toHex(Math.max(id, 0)), { size: 32 }),
          [pad("0x1", { size: 32 })]: pad(toHex(id === -1 ? 32 : 0), {
            size: 32,
          }),
        },
      },
    },
  ]);
  const uri = decodeFunctionResult({
    abi,
    functionName: "tokenURIOf",
    data: result,
  });
  const metadata = JSON.parse(
    Buffer.from(uri.split(",")[1], "base64").toString(),
  );
  const image = metadata.image;
  const svg = image.startsWith("data:image/svg+xml;base64,")
    ? Buffer.from(image.split(",")[1], "base64").toString()
    : decodeURIComponent(image.slice(image.indexOf(",") + 1));
  if (/>#[0-9]*<\/text>/.test(svg))
    throw Error("Unexpected token number in art");
  fs.writeFileSync(
    new URL(
      id === -1 ? "full-house.svg" : id ? `trait-${id}.svg` : "sample.svg",
      dir,
    ),
    svg,
  );
  if (id === 0) {
    const positions = [
      ...svg.matchAll(/<g transform="translate\(([0-9.]+) ([0-9.]+)\)"/g),
    ].slice(0, 13);
    const order = [6, 1, 2, 3, 4, 5, 7, 8, 9, 10, 11, 12, 13];
    const cells = positions.map((m, i) => ({
      family: order[i],
      x: Number(m[1]),
      y: Number(m[2]),
    }));
    fs.writeFileSync(
      new URL("../src/hive-layout.ts", import.meta.url),
      "// Cell geometry and order extracted from the deployed Renderer SVG.\nexport const HIVE_CELLS = " +
        JSON.stringify(cells, null, 2) +
        " as const;\n",
    );
  }
}
fs.writeFileSync(
  new URL("../public/data/art-provenance.json", import.meta.url),
  JSON.stringify(
    {
      sourceCommit: h.sourceCommit,
      rendererAbiHash: renderer.abiHash,
      method:
        "eth_call of deployed Renderer; Registry code override supplies synthetic trait illustrations only; no transaction",
      generatedAt: new Date().toISOString(),
      files: 27,
    },
    null,
    2,
  ) + "\n",
);
console.log(
  "Saved 27 SVGs generated by deployed Renderer (full-house.svg: 25 catalog and 32 community facts); no token-id SVG text.",
);
